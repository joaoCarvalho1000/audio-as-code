"""Build an original listening/target-player pack, without claiming human acceptance."""

from __future__ import annotations

import argparse
import hashlib
import html
import json
from pathlib import Path

if __name__ == "__main__":
    from listening_evaluation import generate as auditions
    from pending_audio_experiments import generate as experiments
else:
    from examples.listening_evaluation import generate as auditions
    from examples.pending_audio_experiments import generate as experiments


def generate(output: Path) -> dict:
    """Preserve all prior packs. Scores, sidecars and provenance travel with audio."""
    output.mkdir(parents=True, exist_ok=False)
    auditions(output / "auditions")
    experiments(output / "experiments")
    cards = []
    for file in sorted(output.rglob("*.wav")):
        relative = file.relative_to(output).as_posix()
        loop = file.name in {"dry-cycle.wav", "wet-cycle.wav"}
        cards.append(
            f"<article><h2>{html.escape(file.stem)}</h2>"
            f'<audio controls preload="none" {"loop" if loop else ""} '
            f'src="{relative}"></audio> <a download href="{relative}">WAV</a>'
            + ("<p>Native loop enabled. Observe at least three wraps.</p>" if loop else "")
            + "</article>"
        )
    (output / "index.html").write_text(
        '<!doctype html><html lang="en"><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        "<title>Original audio review pack</title><h1>Original audio review pack</h1>"
        "<p>Human listening: not_listened. Browser timing observations do not establish "
        "audibility or sample-continuous hardware output. Use headphones or speakers, "
        "record your name, date, player/version and equipment separately.</p>"
        "<p>Compare onset, sustain, release, recognizability and artifacts for every "
        "audition. Compare lifted, half and held pedal after each key release. Listen "
        "to dry and wet loops across three joins, then compare their two-cycle previews. "
        "Retain exact filenames and timestamps for observations.</p>"
        + "".join(cards)
        + "<h2>Target-player observations</h2><p>Wraps are sampled by animation frames; "
        "background throttling can miss them and manual backward seeks can count as wraps. "
        "Do not seek during the observation. No audio output capture is performed.</p>"
        '<button id="save">Save browser observations</button><pre id="observations"></pre>'
        '<script src="review.js" defer></script></html>',
        encoding="utf-8",
    )
    (output / "review.js").write_text(
        """'use strict';
const record = {userAgent:navigator.userAgent, started:new Date().toISOString(),
  humanListening:'not_listened', files:{}};
window.reviewObservations = record;
document.querySelectorAll('audio').forEach(audio => {
  const key = audio.getAttribute('src');
  const data = record.files[key] = {loop:audio.loop, wraps:[], errors:[], playing:0};
  let previous = 0, sampled = 0;
  audio.addEventListener('playing', () => data.playing++);
  audio.addEventListener('error', () => data.errors.push(audio.error?.code));
  function tick(now) {
    if (!audio.paused && !audio.seeking) {
      const current = audio.currentTime;
      if (audio.loop && previous > audio.duration * .75 && current < audio.duration * .25) {
        data.wraps.push({before:previous, after:current, intervalMs:now-sampled,
          duration:audio.duration, observedAt:new Date().toISOString()});
      }
      previous = current; sampled = now;
    }
    document.getElementById('observations').textContent = JSON.stringify(record, null, 2);
    requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
});
document.getElementById('save').addEventListener('click', () => {
  const url = URL.createObjectURL(new Blob([JSON.stringify(record,null,2)],
    {type:'application/json'}));
  const link = document.createElement('a');
  link.href = url; link.download = 'browser-observations.json'; link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});
""",
        encoding="utf-8",
    )
    manifest = {
        "protocol": 1,
        "material": "Original gestures and studies generated by the included source tooling",
        "human_listening": "not_listened",
        "tool_source_hashes": {
            name: hashlib.sha256(Path(__file__).with_name(name).read_bytes()).hexdigest()
            for name in (
                "audio_review_pack.py",
                "listening_evaluation.py",
                "pending_audio_experiments.py",
            )
        },
        "files": {
            file.relative_to(output).as_posix(): hashlib.sha256(file.read_bytes()).hexdigest()
            for file in sorted(output.rglob("*"))
            if file.is_file()
        },
    }
    (output / "pack.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    print(json.dumps(generate(parser.parse_args().output)))
